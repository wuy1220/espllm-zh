def zh_clauses(kws):
    """中文帧的关键词规格 -> 子句列表。

    ["a", "b"]        -> [["a", "b"]]        单子句，任一命中即可
    [["a"], ["b"]]    -> [["a"], ["b"]]      多子句，每一句都必须命中
    []                -> []                  没有关键词（只按长度兜）

    生成器和覆盖脚本都从这里取语义，所以两者的"命中"定义不会漂移。
    """
    if not kws:
        return []
    return [list(kws)] if isinstance(kws[0], str) else [list(c) for c in kws]

if __name__ == "__main__":
    nz = sum(sum(len(c) for c in zh_clauses(r[2])) for r in ZH_RULES)
    rz = sum(len(r[3]) for r in ZH_RULES)
    print(f"zh frames: {len(ZH_RULES)}  keyword phrases: {nz}  replies: {rz}")
    for label, gate, kws, reps in ZH_RULES:
        cls = zh_clauses(kws)
        shape = "%d 子句" % len(cls) if len(cls) > 1 else "%d 词" % len(cls)
        print(f"  {label:14s} gate={gate:4d}  {shape:6s} {len(reps)} 回")
