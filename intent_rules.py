# ---- 概念名词门（2026-10-22 过度拦截实测后加）--------------------------------
#
# 问题：167 条模型训练过的问句里，35 条（21%）被规则帧半路截走，其中 24 条
# 模型本来答得对（_probe_overrule.py 实测）——「你会冻东西吗」「大酱在哪」
# 「你的符卡呢」全被 capability/friend/spell 帧当成了元问题。根因：帧的关键词
# 是谓词（你会/认识/在哪），概念问句和元问句共享同一套谓词。
#
# 解法：输入里出现**已配置概念的名词** = 用户在问模型学过的东西，名词类帧
# 一律让位。这正是三层分工的边界——模型管已配置概念，规则管问句类型；
# 「这个名词学没学过」模型自己判不了（induction head 缺失，实测抄输入 0/16），
# 但固件查表是 O(名词数) 次 strstr_P，输入 <64 B，成本可忽略。
#
# 名词表是 gen_react_corpus.CONCEPTS 各概念名词的并集，四处刻意偏离：
#   * 去掉自我介绍的「你/名字」——「你」出现在几乎每个输入里，进门=门没有；
#   * 补 冻/冻住/冷/湖/下雪——语料名词表里没有，但它们是冰/湖/冬天概念
#     真实会被问到的词（「你会冻东西吗」「湖有多大」两条纯损失就栽在这）；
#   * 不加打招呼的「你好/早上好」——「你好，帮我写作业」会被误门，问候帧的
#     收窄靠删关键词（那 5 条全是打招呼的训练问法），不靠门。
