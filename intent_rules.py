"""Intent rules as data: the single source for both the C++ tables and the
coverage harness.

English is gone
---------------
This file used to carry ~400 English phrases across 20 intents (sad, insult,
greeting, ...) for the English Chatty model. The device now runs a Chinese
Cirno model whose lines already live in the weights, so those frames were pure
ballast: they still fired on English input and answered with a canned English
sentence, which reads as a language switch mid-conversation
("hi" -> "Hi! I'm Chatty, a tiny story bot."). They went out together with
prep_intents.py and coverage_rules.py. What remains is the Chinese layer.

Why the Chinese layer exists at all
-----------------------------------
The model is 2.17M ternary weights. Measured on out-of-canned inputs its
pairwise normalised KL is 0.017 -- it barely conditions on what it was just
told. Identity, nicknames, touching, being called an idiot, weird questions:
those must land somewhere, and 0 ms / zero flash is a better answer than
"sampled from the marginal". Rote answers also come out of the weights now
(89-line stance lexicon), so this layer is deliberately small: a frame earns
its place only if the model structurally cannot do it.

Matching
--------
Chinese has no spaces, so `contains_word` degenerates to a plain substring
test (a CJK byte is >= 0x80 and is_word_char is false) -- exactly what we want.
Frame length gates are in **bytes**: one hanzi is 3 B, so gate 24 = 8 hanzi.
0 means no gate, a negative value is a lower bound (used by zh_listen).
Several replies per frame are picked at random on the device (pick_flash), so
asking the same thing twice does not repeat the same sentence.
"""
