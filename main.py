BINARY_WEIGHTS = WEIGHT_BITS <= 1.0
CONTRASTIVE_WEIGHT = float(os.environ.get("ESPGPT_CONTRASTIVE_WEIGHT", "0"))
PREFERENCE_WEIGHT = float(os.environ.get("ESPGPT_PREFERENCE_WEIGHT", "0"))
PREFERENCE_MARGIN = float(os.environ.get("ESPGPT_PREFERENCE_MARGIN", "0.5"))


def preference_loss(model, pos_x, pos_y, neg_x, neg_y):
    """Prefer the positive answer likelihood for aligned prompt windows."""
    if neg_x is None or neg_y is None:
        return pos_x.new_zeros(())
    pos_logits, _, _ = model(pos_x, pos_y, return_hidden=True)
    # The preference corpus has the same prompt, so compare full-window token
    # likelihoods only after the prompt mask. Reuse positive labels as the
    # target mask; differing answer lengths are normalized by valid token count.
    neg_logits, _, _ = model(neg_x, neg_y, return_hidden=True)
    lp = F.log_softmax(pos_logits.float(), dim=-1)
    ln = F.log_softmax(neg_logits.float(), dim=-1)
    vp = pos_y != -100
    vn = neg_y != -100
    ip = pos_y.clamp_min(0)
    inn = neg_y.clamp_min(0)
    sp = (lp.gather(-1, ip.unsqueeze(-1)).squeeze(-1) * vp).sum(1) / vp.sum(1).clamp_min(1)
    sn = (ln.gather(-1, inn.unsqueeze(-1)).squeeze(-1) * vn).sum(1) / vn.sum(1).clamp_min(1)
    return F.relu(PREFERENCE_MARGIN - (sp - sn)).mean()


def supervised_contrastive_loss(hidden, labels, temperature=0.2):
    """Cosine supervised contrastive loss over valid concept-labelled windows."""
    valid = labels >= 0
    if int(valid.sum()) < 2:
        return hidden.new_zeros(())
    z = F.normalize(hidden[valid], dim=-1)
    y = labels[valid]
    sim = z @ z.t() / temperature
    eye = torch.eye(sim.size(0), device=sim.device, dtype=torch.bool)
    sim = sim.masked_fill(eye, float("-inf"))
    pos = (y[:, None] == y[None, :]) & ~eye
    counts = pos.sum(dim=1)
    keep = counts > 0
    if not bool(keep.any()):
        return hidden.new_zeros(())
    logp = sim - torch.logsumexp(sim, dim=1, keepdim=True)
    return -(logp.masked_fill(~pos, 0.0).sum(dim=1)[keep] / counts[keep]).mean()


class BitLinear(nn.Module):
    def __init__(
        self,
        in_features: int,
        out_features: int,
        bias: bool = False,
        group_size: int = 64,
    ):
        super().__init__()
        self.in_features = in_features
        self.out_features = out_features
        self.group_size = group_size
        self.weight = nn.Parameter(torch.empty(out_features, in_features))
        if bias:
            self.bias = nn.Parameter(torch.zeros(out_features))
        else:
            self.register_parameter("bias", None)
        nn.init.kaiming_uniform_(self.weight, a=math.sqrt(5))

    def _quantize_weight(self, w: torch.Tensor):
        out, n = w.shape
        n_groups = math.ceil(n / self.group_size)
        padded_n = n_groups * self.group_size
        w_pad = F.pad(w, (0, padded_n - n)) if padded_n != n else w
        wg = w_pad.view(out, n_groups, self.group_size)
        scale = wg.abs().mean(dim=-1, keepdim=True).clamp(min=1e-5)
        if BINARY_WEIGHTS:
            # No zero state: every connection must vote. Scale is still the
            # per-group mean |w|, the standard BNN factor (scale * sign).
            w_q = torch.where(wg >= 0, torch.ones_like(wg), -torch.ones_like(wg))
        else:
            w_q = torch.clamp(torch.round(wg / scale), -1, 1)
        w_deq = (w_q * scale).view(out, padded_n)[:, :n]
        return w + (w_deq - w).detach()

    def _quantize_activation(self, x: torch.Tensor):
        scale = (x.abs().max(dim=-1, keepdim=True).values / 127.0).clamp(min=1e-5)
        x_q = torch.clamp(torch.round(x / scale), -128, 127)
        x_deq = x_q * scale
        return x + (x_deq - x).detach()

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        w_fake = self._quantize_weight(self.weight)
        x_fake = self._quantize_activation(x)
        return F.linear(x_fake, w_fake, self.bias)

    def to_inference(self):
        if BINARY_WEIGHTS:
            # The firmware kernel decodes base-3 and has no binary path, so a
            # binary QAT run would export silently wrong weights. Fail loudly
            # instead: set ESPGPT_WEIGHT_BITS back to 1.58, or teach
            # convert_model_to_c.py a 1-bit packing first.
            raise RuntimeError(
                "refusing to export: ESPGPT_WEIGHT_BITS=1 (binary) has no "
                "firmware dequantiser; the shipped kernel is ternary only")
        return BitLinearInference(
            self.in_features,
            self.out_features,
            self.weight.detach(),
            self.bias.detach() if self.bias is not None else None,
            self.group_size,
        )


class BitLinearInference(nn.Module):
    def __init__(self, in_features, out_features, weight, bias=None, group_size=64):
        super().__init__()
        self.in_features = in_features
        self.out_features = out_features
        self.group_size = group_size

        out, n = weight.shape
        n_groups = math.ceil(n / group_size)
        padded_n = n_groups * group_size
        w_pad = F.pad(weight, (0, padded_n - n)) if padded_n != n else weight
        wg = w_pad.view(out, n_groups, group_size)
        scale = wg.abs().mean(dim=-1, keepdim=True).clamp(min=1e-5)
        w_q = torch.clamp(torch.round(wg / scale), -1, 1).to(torch.int8)
        w_q = w_q.view(out, padded_n)[:, :n]
        scale = scale.squeeze(-1)

        self.register_buffer("qweight", w_q)
        self.register_buffer("scale", scale.half())
        if bias is not None:
            self.bias = nn.Parameter(bias.detach().half())
        else:
            self.register_parameter("bias", None)

    def _dequantize_weight(self):
        w = self.qweight.float()
        groups = torch.arange(self.in_features, device=w.device) // self.group_size
        return w * self.scale.float()[:, groups]

    def forward(self, x):
        x_scale = (x.abs().max(dim=-1, keepdim=True).values / 127.0).clamp(min=1e-5)
        x_q = torch.clamp(torch.round(x / x_scale), -128, 127)
        x_deq = x_q * x_scale
        bias = self.bias.float() if self.bias is not None else None
        return F.linear(x_deq, self._dequantize_weight(), bias)


def precompute_freqs(head_dim: int, max_seq_len: int, device):
    theta = 10000.0 ** (-torch.arange(0, head_dim, 2, device=device).float() / head_dim)
    t = torch.arange(max_seq_len, device=device).float()
    freqs = torch.outer(t, theta)
    return freqs.cos(), freqs.sin()


def apply_rope(x: torch.Tensor, cos: torch.Tensor, sin: torch.Tensor):
    x1 = x[..., 0::2]
    x2 = x[..., 1::2]
    B, H, T, D = x.shape
    cos = cos[:T].unsqueeze(0).unsqueeze(0)
    sin = sin[:T].unsqueeze(0).unsqueeze(0)
    return torch.cat([x1 * cos - x2 * sin, x1 * sin + x2 * cos], dim=-1)


class SwiGLUMLP(nn.Module):
    def __init__(self, n_embd: int, hidden: int, dropout: float, group_size: int = 64):
        super().__init__()
        self.gate_proj = BitLinear(n_embd, hidden, bias=False, group_size=group_size)
        self.up_proj = BitLinear(n_embd, hidden, bias=False, group_size=group_size)
        self.down_proj = BitLinear(hidden, n_embd, bias=False, group_size=group_size)
        self.drop = nn.Dropout(dropout)

    def forward(self, x):
        gate = F.silu(self.gate_proj(x))
        up = self.up_proj(x)
        return self.drop(self.down_proj(gate * up))


# --- batched MoE -------------------------------------------------------------
# The per-expert loop launches 3 tiny GEMMs per expert per token block, and each
# expert only sees a few hundred of the 16384 tokens, so the step is dominated by
# dispatch overhead rather than math.  Sorting tokens by expert and running one
# batched GEMM per projection keeps the arithmetic identical while cutting the
# call count by an order of magnitude.
MOE_BATCHED = os.environ.get("ESPGPT_MOE_BATCHED", "1") != "0"

# Bucket width for the block-bucketed path (see forward()).  The old scheme
# padded every expert's bucket to the *largest* expert, which is fine on
# uniformly random tokens (max/mean ~1.7x) but pathological on real data:
# measured max/mean 7.7-11.5x per layer, so the batched GEMM was doing 9x the
# necessary work and the duplicate-index scatter dominated the step.
# Fixed-width blocks make the waste depend on the block width instead of on the
# longest expert: 0 = keep the old padded scheme (A/B only).
MOE_BLOCK = int(os.environ.get("ESPGPT_MOE_BLOCK", "128"))

# Diagnostics hook: set to a list from a bench script and each batched-MoE
# forward appends (mean, max, n_experts) of the routing counts.  Left as None
# in training so the branch costs nothing.
MOE_STATS = None


def _bitlinear_batched(x, w, group_size):
    """BitLinear forward for a stack of expert weights, shape [E, out, in].

    Mirrors BitLinear.forward exactly: per-group absmean weight scale, ternary
    (or binary) weights with a straight-through estimator, per-token int8
    activation quantisation.
    """
    E, out, n = w.shape
    n_groups = math.ceil(n / group_size)
    padded = n_groups * group_size
    if padded != n:
        w = F.pad(w, (0, padded - n))
    wg = w.view(E, out, n_groups, group_size)
    scale = wg.abs().mean(dim=-1, keepdim=True).clamp(min=1e-5)
    if BINARY_WEIGHTS:
        w_q = torch.where(wg >= 0, torch.ones_like(wg), -torch.ones_like(wg))
    else:
        w_q = torch.clamp(torch.round(wg / scale), -1, 1)
    w_padded = w
    w_deq = (w_q * scale).view(E, out, padded)[..., :n]
    w_orig = w_padded[..., :n]
    w_fake = w_orig + (w_deq - w_orig).detach()

    x_scale = (x.abs().max(dim=-1, keepdim=True).values / 127.0).clamp(min=1e-5)
    x_q = torch.clamp(torch.round(x / x_scale), -128, 127)
    x_fake = x + (x_q * x_scale - x).detach()
    return torch.bmm(x_fake, w_fake.transpose(1, 2))


class SparseMoEBlock(nn.Module):
    def __init__(
        self,
        n_embd: int,
        n_experts: int,
        hidden: int,
        dropout: float,
        group_size: int = 64,
    ):
        super().__init__()
        self.n_experts = n_experts
        self.router = nn.Linear(n_embd, n_experts, bias=False)
        self.experts = nn.ModuleList(
            [SwiGLUMLP(n_embd, hidden, dropout, group_size) for _ in range(n_experts)]
        )
        if SHARED_EXPERT:
            self.shared_expert = SwiGLUMLP(n_embd, hidden, dropout, group_size)
            self.shared_scale = nn.Parameter(torch.zeros(()))

    def forward(self, x):
        B, T, C = x.size()
        x_flat = x.view(-1, C)
        router_logits = self.router(x_flat)
        routing_probs = F.softmax(router_logits, dim=-1)
        top1_probs, top1_indices = torch.max(routing_probs, dim=-1)
        if MOE_BATCHED and MOE_BLOCK > 0:
            # Fixed-width block bucketing.  Tokens are sorted by expert, then
            # each expert's run is cut into blocks of exactly `cap` slots, so
            # the wasted slots are one partial block per expert instead of
            # "every bucket as long as the busiest expert".  Measured on the
            # corpus, padding drops from 7.7-11.5x to ~1.15x.
            #
            # Because (blk_start[e] + j // cap) * cap + j % cap ==
            # blk_start[e] * cap + j, the flat slot of the j-th token of expert
            # e is just an affine function of j -- no division needed, and every
            # slot is a distinct token, so both the scatter in and the gather
            # out are duplicate-free (the old scheme scattered into a bucket
            # padded with copies of token 0, whose backward accumulated over
            # 10x the real rows).
            n_tok = x_flat.size(0)
            E = self.n_experts
            cap = MOE_BLOCK
            counts = torch.bincount(top1_indices, minlength=E)
            if MOE_STATS is not None:
                MOE_STATS.append(
                    (float(counts.float().mean()), int(counts.max()), E)
                )
            starts = torch.cumsum(counts, 0) - counts
            order = torch.argsort(top1_indices, stable=True)
            sorted_e = top1_indices[order]
            within = torch.arange(n_tok, device=x.device) - starts[sorted_e]

            n_blk = (counts + cap - 1) // cap
            blk_start = torch.cumsum(n_blk, 0) - n_blk
            blk_of_expert = torch.repeat_interleave(
                torch.arange(E, device=x.device), n_blk
            )
            total_blk = int(n_blk.sum())
            slot = blk_start[sorted_e] * cap + within

            src = x_flat.index_select(0, order)
            buf = x_flat.new_zeros(total_blk * cap, C).index_copy(0, slot, src)
            tok = buf.view(total_blk, cap, C)

            gs = self.experts[0].gate_proj.group_size
            w_gate = torch.stack([e.gate_proj.weight for e in self.experts])
            w_up = torch.stack([e.up_proj.weight for e in self.experts])
            w_down = torch.stack([e.down_proj.weight for e in self.experts])
            w_gate = w_gate.index_select(0, blk_of_expert)
            w_up = w_up.index_select(0, blk_of_expert)
            w_down = w_down.index_select(0, blk_of_expert)

            gate = F.silu(_bitlinear_batched(tok, w_gate, gs))
            up = _bitlinear_batched(tok, w_up, gs)
            hid = self.experts[0].drop(gate * up)
            y_blk = _bitlinear_batched(hid, w_down, gs)
            y_sorted = y_blk.reshape(-1, C).index_select(0, slot)
            scale = top1_probs[order].unsqueeze(-1)
            y_sorted = y_sorted * (scale - scale.detach() + 1.0)
            # order[i] is the token that sorted slot i belongs to, so the
            # inverse permutation puts the outputs back in token order.
            inv = torch.empty_like(order)
            inv[order] = torch.arange(n_tok, device=x.device)
            out_flat = y_sorted.index_select(0, inv)
        elif MOE_BATCHED:
            # Old scheme, kept for A/B: one bucket per expert, all padded to
            # the busiest expert.  Pathological on real routing -- see above.
            n_tok = x_flat.size(0)
            E = self.n_experts
            counts = torch.bincount(top1_indices, minlength=E)
            if MOE_STATS is not None:
                MOE_STATS.append(
                    (float(counts.float().mean()), int(counts.max()), E)
                )
            starts = torch.cumsum(counts, 0) - counts
            order = torch.argsort(top1_indices, stable=True)
            local = torch.arange(n_tok, device=x.device) - starts[top1_indices[order]]
            rows = torch.zeros((E, int(counts.max())), dtype=torch.long, device=x.device)
            rows[top1_indices[order], local] = order
            valid = (
                torch.arange(rows.size(1), device=x.device).unsqueeze(0)
                < counts.unsqueeze(1)
            )
            tok = x_flat[rows]

            gs = self.experts[0].gate_proj.group_size
            w_gate = torch.stack([e.gate_proj.weight for e in self.experts])
            w_up = torch.stack([e.up_proj.weight for e in self.experts])
            w_down = torch.stack([e.down_proj.weight for e in self.experts])
            gate = F.silu(_bitlinear_batched(tok, w_gate, gs))
            up = _bitlinear_batched(tok, w_up, gs)
            hid = self.experts[0].drop(gate * up)
            expert_out = _bitlinear_batched(hid, w_down, gs)[valid]
            scale = top1_probs[order].unsqueeze(-1)
            expert_out = expert_out * (scale - scale.detach() + 1.0)
            out_flat = torch.zeros_like(x_flat).index_copy(0, order, expert_out)
        else:
            out_flat = torch.zeros_like(x_flat)
            dummy = x_flat[:1].detach()
            for i, expert in enumerate(self.experts):
                mask = top1_indices == i
                if mask.any():
                    expert_in = x_flat[mask]
                    expert_out = expert(expert_in)
                    scale = top1_probs[mask].unsqueeze(-1)
                    expert_out = expert_out * (scale - scale.detach() + 1.0)
                    out_flat[mask] = expert_out
                else:
                    out_flat = out_flat + 0.0 * expert(dummy).sum()
        if SHARED_EXPERT:
            out_flat = out_flat + self.shared_scale * self.shared_expert(x_flat)
        out = out_flat.view(B, T, C)
        route_frac = torch.bincount(
            top1_indices, minlength=self.n_experts
        ).float() / top1_indices.size(0)
        prob_mean = routing_probs.mean(dim=0)
        aux_loss = self.n_experts * torch.sum(route_frac * prob_mean)
        return out, aux_loss


class CausalSelfAttention(nn.Module):
    def __init__(self, n_embd: int, n_head: int, dropout: float, group_size: int = 64):
        super().__init__()
        assert n_embd % n_head == 0
        self.n_head = n_head
        self.head_dim = n_embd // n_head
        self.qkv = BitLinear(
            n_embd,
            n_embd + 2 * n_kv_head * self.head_dim,
            bias=False,
            group_size=group_size,
        )
        self.proj = BitLinear(n_embd, n_embd, bias=False, group_size=group_size)
        self.attn_drop = nn.Dropout(dropout)
        self.resid_drop = nn.Dropout(dropout)
        self.register_buffer(
            "mask",
            torch.tril(torch.ones(block_size, block_size)).view(
                1, 1, block_size, block_size
            ),
            persistent=False,
        )

    def forward(self, x, cos, sin, shared_kv=None, return_kv=False):
        B, T, C = x.size()
        qkv = self.qkv(x)
        q, k, v = qkv.split(
            [
                self.n_head * self.head_dim,
                n_kv_head * self.head_dim,
                n_kv_head * self.head_dim,
            ],
            dim=2,
        )
        q = q.view(B, T, self.n_head, self.head_dim).transpose(1, 2)
        k = k.view(B, T, n_kv_head, self.head_dim).transpose(1, 2)
        v = v.view(B, T, n_kv_head, self.head_dim).transpose(1, 2)
        q = apply_rope(q, cos, sin)
        if shared_kv is None:
            k = apply_rope(k, cos, sin)
        else:
            k, v = shared_kv
        cache_kv = (k, v)
        k = k.repeat_interleave(self.n_head // n_kv_head, dim=1)
        v = v.repeat_interleave(self.n_head // n_kv_head, dim=1)
        att = (q @ k.transpose(-2, -1)) / math.sqrt(self.head_dim)
        att = att.masked_fill(self.mask[:, :, :T, :T] == 0, float("-inf"))
        att = F.softmax(att, dim=-1)
        att = self.attn_drop(att)
        y = att @ v
        y = y.transpose(1, 2).contiguous().view(B, T, C)
        y = self.resid_drop(self.proj(y))
        if return_kv:
            return y, cache_kv
        return y


class RMSNorm(nn.Module):
    def __init__(self, dim: int, eps: float = 1e-5):
        super().__init__()
        self.eps = eps
        self.weight = nn.Parameter(torch.ones(dim))

    def forward(self, x: torch.Tensor):
        norm_x = x * torch.rsqrt(x.pow(2).mean(-1, keepdim=True) + self.eps)
        return norm_x * self.weight


class Block(nn.Module):
    def __init__(
        self,
        n_embd: int,
        n_head: int,
        n_experts: int,
        hidden: int,
        dropout: float,
        group_size: int = 64,
    ):
        super().__init__()
        self.ln1 = RMSNorm(n_embd)
        self.attn = CausalSelfAttention(n_embd, n_head, dropout, group_size)
        self.ln2 = RMSNorm(n_embd)
        self.mlp = SparseMoEBlock(n_embd, n_experts, hidden, dropout, group_size)

    def forward(self, x, cos, sin, shared_kv=None, return_kv=False):
        attn_out = self.attn(self.ln1(x), cos, sin, shared_kv=shared_kv,
                             return_kv=return_kv)
        if return_kv:
            attn_out, kv = attn_out
        x = x + attn_out
        mlp_out, aux_loss = self.mlp(self.ln2(x))
        x = x + mlp_out
        if return_kv:
            return x, aux_loss, kv
        return x, aux_loss


class Transformer(nn.Module):
    def __init__(self, group_size: int = 64):
        super().__init__()
        self.group_size = group_size
        self.tok_emb = nn.Embedding(vocab_size, n_embd)
        self.drop = nn.Dropout(dropout)
        self.blocks = nn.ModuleList(
            [
                Block(
                    n_embd,
                    n_head,
                    n_experts,
                    moe_hidden,
                    dropout,
                    group_size=group_size,
                )
                for _ in range(n_layer)
            ]
        )
        self.ln_f = RMSNorm(n_embd)
        self.lm_head = BitLinear(n_embd, vocab_size, bias=False, group_size=group_size)
        self.lm_head.weight = self.tok_emb.weight
        head_dim = n_embd // n_head
        cos, sin = precompute_freqs(head_dim, block_size, device="cpu")
        self.register_buffer("rope_cos", cos, persistent=True)
        self.register_buffer("rope_sin", sin, persistent=True)
        self.apply(self._init_weights)

    def _init_weights(self, module):
        if isinstance(module, nn.Linear):
            torch.nn.init.normal_(module.weight, mean=0.0, std=0.02)
            if module.bias is not None:
                torch.nn.init.zeros_(module.bias)
        elif isinstance(module, BitLinear):
            torch.nn.init.normal_(module.weight, mean=0.0, std=0.02)

    def forward(self, idx, targets=None, return_hidden=False):
        B, T = idx.size()
        x = self.tok_emb(idx)
        cos = self.rope_cos[:T].to(x.device)
        sin = self.rope_sin[:T].to(x.device)
        total_aux_loss = 0.0
        shared_kv = None
        for layer_idx, block in enumerate(self.blocks):
            use_cla = CLA and (layer_idx % 2 == 1)
            block_out = block(
                x, cos, sin,
                shared_kv=shared_kv if use_cla else None,
                return_kv=CLA,
            )
            if CLA:
                x, aux_loss, block_kv = block_out
                if not use_cla:
                    shared_kv = block_kv
            else:
                x, aux_loss = block_out
            total_aux_loss += aux_loss
        x = self.ln_f(x)
        logits = self.lm_head(x)
        loss = None
        if targets is not None:
            ce_loss = F.cross_entropy(
                logits.view(-1, logits.size(-1)),
                targets.view(-1),
                label_smoothing=label_smoothing,
            )
            loss = ce_loss + 0.01 * total_aux_loss
        if return_hidden:
            return logits, loss, x
        return logits, loss

    @torch.no_grad()
    def generate(self, idx, max_new_tokens, temp=temperature, top_k=1, rep_penalty=1.0):
        prompt_len = len(decode(idx[0].tolist()))
        for _ in range(max_new_tokens):
            idx_cond = idx[:, -block_size:]
            logits, _ = self(idx_cond)
            logits = logits[:, -1, :].clone()
            for token_id in set(idx_cond[0].tolist()):
                score = logits[0, token_id]
                logits[0, token_id] = (
                    score / rep_penalty if score > 0 else score * rep_penalty
                )
            logits = logits / temp
            if top_k > 0 and top_k < logits.size(-1):
                thresh = torch.topk(logits, top_k).values[:, -1, None]
                logits[logits < thresh] = float("-inf")
            probs = F.softmax(logits, dim=-1)
            next_id = torch.multinomial(probs, num_samples=1)
            if next_id.item() == 0:
                break
            idx = torch.cat((idx, next_id), dim=1)
            current_text = decode(idx[0].tolist())
            new_text = current_text[prompt_len:]
            if "\ufffd" not in new_text:
                print(new_text, end="", flush=True)
                prompt_len = len(current_text)
            if "\n" in new_text:
                break
        print()
        return idx


@torch.no_grad()
def estimate_loss():
    model.eval()
    out = {}
    for split in ["train", "val"]:
        losses = []
        for _ in range(eval_iters):
            xb, yb = get_batch(split)
            _, loss = model(xb, yb)
            losses.append(loss.item())
        out[split] = sum(losses) / len(losses)
    if DIST:
        # Average the local estimates across ranks so every rank logs the
        # same global numbers (keeps early-stopping decisions in sync).
        import torch.distributed as dist

        # NCCL needs CUDA tensors, gloo needs CPU tensors.
        _dev = device if torch.cuda.is_available() else "cpu"
        t = torch.tensor([out["train"], out["val"]], device=_dev)
        dist.all_reduce(t, op=dist.ReduceOp.SUM)
        t /= WORLD
        out = {"train": t[0].item(), "val": t[1].item()}
    model.train()
    return out


def convert_to_bitlinear(model: nn.Module) -> nn.Module:
    for name, child in model.named_children():
        if isinstance(child, BitLinear):
            setattr(model, name, child.to_inference())
        else:
            convert_to_bitlinear(child)
    return model


def train():
    global model
    engine = globals().get("engine", None)
    is_main = RANK == 0
    if DIST:
        # Model weights were initialized identically on all ranks (torch seed
        # 1337 at import). Now decorrelate per-rank stochasticity (dropout
        # masks) now that init is done; `random` drives per-rank batch sampling.
        torch.manual_seed(1337 + RANK)
        random.seed(1337 + RANK)
    best_val_loss = float("inf")
    patience_counter = 0

    # Warm start must happen HERE, not in load_model().
    #
    # load_model() is only reached on the interactive path; the `force_train`
    # branch in __main__ calls train() directly and then exits, so a warm
    # start wired up there never ran. Every "warm start" run so far therefore
    # silently trained from random init -- visible only as loss starting at
    # 7.66 instead of ~3.2. Loading after the optimizer is built but before the
    # first step covers both the plain and the DeepSpeed path, since DeepSpeed
    # partitions the parameters it is handed at initialize() time.
    if INIT_CHECKPOINT and os.path.isfile(INIT_CHECKPOINT):
        print(f"Warm start from {INIT_CHECKPOINT}...")
        model.load_state_dict(load_checkpoint(INIT_CHECKPOINT, model,
                                              map_location=device),
                              strict=not SHARED_EXPERT)
        model.to(device)
        # Under DeepSpeed the optimizer holds fp32 master copies created at
        # initialize() time, so pushing the state dict through the engine is
        # what actually makes the loaded weights the ones being optimized.
        # Plain path: engine is None and model.to(device) is enough.
        if engine is not None:
            engine._module.load_state_dict(model.state_dict())
        print("Warm start loaded.")
    elif INIT_CHECKPOINT:
        print(f"Warm start requested but not found: {INIT_CHECKPOINT}")

    # In the deepspeed path `optimizer` is the BASE torch optimizer (see
    # __main__: the DeepSpeedZeroOptimizer wrapper is not a torch Optimizer,
    # so the torch scheduler + manual warmup keep driving the base optimizer,
    # whose param_groups the engine reads at step time). Grad clipping comes
    # from the ds config.
    opt = optimizer
    scheduler = CosineAnnealingLR(opt, T_max=T_MAX, eta_min=lr_min)
    # 余弦退火终点审计（audit 19.3）：把「跑完时的学习率」算出来打一行，别让
    # 调度周期静默地超过训练步数。计划终点 lr =
    #   lr_min + (lr - lr_min) * (1 + cos(pi * max_iters / T_MAX)) / 2
    import math as _math

    _final_lr = lr_min + (lr - lr_min) * (1 + _math.cos(_math.pi * max_iters / T_MAX)) / 2
    print(
        f"lr schedule: warmup {warmup_iters} -> cosine T_max={T_MAX} over "
        f"max_iters={max_iters}; planned final lr {_final_lr:.3e} (lr_min {lr_min:.1e})"
    )
    if T_MAX > max_iters and _T_MAX_ENV:
        print(
            f"  note: T_MAX={T_MAX} > max_iters={max_iters} (explicit override) — "
            f"the cosine will NOT reach lr_min by the end of this run."
        )
    for it in range(start_iter, max_iters + 1):
        if it < warmup_iters:
            warmup_lr = lr * (it + 1) / warmup_iters
            for pg in opt.param_groups:
                pg["lr"] = warmup_lr
        if it % eval_interval == 0:
            losses = estimate_loss()
            # NOTE: losses are identical on all ranks (all-reduced), so every
            # rank updates counters and hits `break` together. Only rank 0
            # prints/saves to avoid duplicate logs and file races.
            if losses["val"] < best_val_loss:
                best_val_loss = losses["val"]
                patience_counter = 0
                if is_main:
                    cur_lr = opt.param_groups[0]["lr"]
                    print(
                        f"iter {it :5d} | train {losses ['train']:.4f} | val {losses ['val']:.4f} "
                        f"| lr {cur_lr :.2e}"
                    )
                    save_checkpoint(model, checkpoint + ".best")
                    print(f"  * new best ({best_val_loss:.4f}) saved")
            else:
                patience_counter += 1
                if is_main:
                    cur_lr = opt.param_groups[0]["lr"]
                    print(
                        f"iter {it :5d} | train {losses ['train']:.4f} | val {losses ['val']:.4f} "
                        f"| lr {cur_lr :.2e}"
                    )
                if patience_counter >= patience:
                    if is_main:
                        print("Early stopping triggered.")
                    break
        xb, yb, batch_labels, pref_x, pref_y = get_batch("train", with_meta=True)
        try:
            if engine is not None:
                logits, loss = engine(xb, yb)
                engine.backward(loss)
                engine.step()
            else:
                logits, loss, hidden = model(xb, yb, return_hidden=True)
                if CONTRASTIVE_WEIGHT:
                    c_loss = supervised_contrastive_loss(hidden.mean(dim=1), batch_labels)
                    loss = loss + CONTRASTIVE_WEIGHT * c_loss
                if PREFERENCE_WEIGHT:
                    loss = loss + PREFERENCE_WEIGHT * preference_loss(model, xb, yb, pref_x, pref_y)
                optimizer.zero_grad(set_to_none=True)
                loss.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
                optimizer.step()
        except RuntimeError as e:
            if "out of memory" in str(e).lower():
                if is_main:
                    print(f"  [OOM at iter {it}] skipping batch, clearing cache")
                if torch.cuda.is_available():
                    torch.cuda.empty_cache()
                if engine is not None:
                    engine.optimizer.zero_grad()
                else:
                    optimizer.zero_grad(set_to_none=True)
                continue  # skip this iteration
            else:
                raise  # re-raise non-OOM errors
        if it >= warmup_iters:
            scheduler.step()
    if not is_main:
        if DIST:
            import torch.distributed as dist

            dist.barrier()
        return
    save_checkpoint(model, checkpoint)
    print("Full-precision model saved to", checkpoint)
    if os.path.isfile(checkpoint + ".best"):
        model.load_state_dict(load_checkpoint(checkpoint + ".best", model, map_location=device),
                              strict=not SHARED_EXPERT)
        model.eval()
        print("Loaded best checkpoint for quantization.")
    q_model = convert_to_bitlinear(deepcopy(model))
    with gzip.open(checkpoint + ".quantized", "wb") as f:
        torch.save(q_model, f)
    quant_size = os.path.getsize(checkpoint + ".quantized")
    print(
        f"Quantized model saved → {checkpoint }.quantized  ({quant_size /1024 :.1f} KB)"
    )
    if DIST:
        import torch.distributed as dist

        dist.barrier()


def load_model():
    global model
    # Explicit warm start takes precedence over everything else. It must not go
    # through the .quantized path: BitLinearInference modules hold int8 buffers,
    # which cannot be optimized. Load the full-precision weights instead.
    if INIT_CHECKPOINT and os.path.isfile(INIT_CHECKPOINT):
        print(f"Warm start from {INIT_CHECKPOINT}...")
        model.load_state_dict(load_checkpoint(INIT_CHECKPOINT, model, map_location=device),
                              strict=not SHARED_EXPERT)
        model.to(device)
        print("Warm start loaded.")
        return
    if os.path.isfile(checkpoint + ".quantized"):
        print("Loading quantized model (primary)...")
        with gzip.open(checkpoint + ".quantized", "rb") as f:
            model = torch.load(f, map_location=device, weights_only=False)
        model.to(device)
        model.eval()
        print("Quantized model ready.")
        return
    src = None
    if os.path.isfile(checkpoint + ".best"):
        src = checkpoint + ".best"
    elif os.path.isfile(checkpoint):
        src = checkpoint
    if src:
        print(f"Loading unquantized checkpoint from {src } and quantizing...")
        model.load_state_dict(load_checkpoint(src, model, map_location=device),
                              strict=not SHARED_EXPERT)
        model.eval()
        q_model = convert_to_bitlinear(deepcopy(model))
        with gzip.open(checkpoint + ".quantized", "wb") as f:
            torch.save(q_model, f)
        print(f"Quantized and saved → {checkpoint }.quantized")
        with gzip.open(checkpoint + ".quantized", "rb") as f:
            model = torch.load(f, map_location=device, weights_only=False)
        model.to(device)
        model.eval()
        return
    print("No checkpoint found — training from scratch...")
    train()
    load_model()


