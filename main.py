def _parse_extra(spec):
    out = []
    for part in (spec or "").split(","):
        part = part.strip()
        if not part:
            continue
        path, _, share = part.rpartition(":")
        if not path or not share:
            raise SystemExit(f"ESPGPT_EXTRA: expected path:share, got {part!r}")
        out.append((path, float(share)))
    return out


