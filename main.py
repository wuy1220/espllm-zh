# Weight precision for QAT. 1.58 = ternary {-1,0,+1} (the shipped setting);
# 1.0 = binary {-1,+1}. Exposed as an env switch so the 1-bit-vs-1.58 decision
# can be settled by two otherwise identical training runs instead of by argument.
