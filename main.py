# ── Checkpoint architecture tagging ────────────────────────────────────────────
# The shipped checkpoints are bare state_dicts: nothing inside records the
# architecture they belong to. That is the root cause of the config drift this
# file previously carried (declared n_experts=32 / block_size=32 vs the 20 / 64
# actually baked into model_weights.hpp). Saving the shape alongside the weights
# makes a mismatch detectable instead of silent.
ARCH_KEY = "__arch__"


def arch_spec():
    return {
        "target": TARGET,
        "block_size": block_size,
        "n_layer": n_layer,
        "n_head": n_head,
        "n_kv_head": n_kv_head,
        "n_embd": n_embd,
        "n_experts": n_experts,
        "moe_hidden": moe_hidden,
        "group_size": qat_group_size,
        "vocab_size": vocab_size,
        "shared_expert": SHARED_EXPERT,
        "cla": CLA,
    }


def save_checkpoint(model, path):
    """Save weights plus the architecture that produced them."""
    torch.save({ARCH_KEY: arch_spec(), **model.state_dict()}, path)


def load_checkpoint(path, model, map_location="cpu"):
    """Load weights, verifying the recorded architecture matches this run.

    A mismatch raises instead of silently loading: the shapes may still happen
    to broadcast, but the exported C header would then describe a model the
    firmware cannot run.
    """
    obj = torch.load(path, map_location=map_location, weights_only=False)
    if isinstance(obj, dict) and ARCH_KEY in obj:
        saved = obj[ARCH_KEY]
        want = arch_spec()
        diffs = {
            k: (saved.get(k), want[k])
            for k in want
            if k in saved and saved[k] != want[k]
        }
        # block_size is the one field a warm start may legitimately change: the
        # weights do not depend on it, only the rope table does, and that table
        # is regenerated below from the new block_size. Everything else changes
        # tensor shapes, so it still refuses.
        block_delta = diffs.pop("block_size", None)
        if diffs:
            detail = ", ".join(f"{k}: ckpt={a} vs cfg={b}" for k, (a, b) in diffs.items())
            raise SystemExit(
                f"Architecture mismatch loading {path}:\n  {detail}\n"
                f"Refusing to load. Re-train with matching settings or restore the "
                f"original config."
            )
        if block_delta is not None:
            print(f"  context extension: block_size {block_delta[0]} -> "
                  f"{block_delta[1]} (weights unchanged, rope table regenerated)")
        state = {k: v for k, v in obj.items() if k != ARCH_KEY}
        # The rope tables are a pure function of block_size, not learned
        # parameters. Loading a 64-token checkpoint into a 128-token run is the
        # whole point of a context-extension fine-tune, and a strict load would
        # refuse over a buffer whose first 64 rows are already identical. Keep
        # the key (strict loading requires it) but hand back the freshly
        # computed table instead of the shorter saved one.
        live = model.state_dict()
        for _k in ("rope_cos", "rope_sin"):
            if _k in state and _k in live and state[_k].shape != live[_k].shape:
                print(f"  regenerating {_k}: ckpt {tuple(state[_k].shape)} -> "
                      f"{tuple(live[_k].shape)} for block_size={block_size}")
                state[_k] = live[_k].clone()
        print(f"  checkpoint arch verified: {saved}")
        return state
    # Legacy checkpoint with no metadata: infer the architecture from shapes so
    # the mismatch still surfaces.
    state = obj
    sd = state if not hasattr(state, "state_dict") else state.state_dict()
    tok = sd.get("tok_emb.weight")
    if tok is not None and tok.shape[0] != vocab_size:
        print(
            f"  WARNING: {path} has vocab {tok.shape[0]} but tokenizer yields "
            f"{vocab_size}. Checkpoint predates arch tagging."
        )
    return state

