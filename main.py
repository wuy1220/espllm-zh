def window_from_ids(i):
    """Slice the pre-tokenised stream into one full-length window, as (x, y).

    torch.stack needs tensors, and the id list holds plain ints -- so one
    window is converted here and the batch stacks the results. Building the
    whole batch as a single tensor first would need a nested list, which stack
    rejects for the same reason.
    """
    s = story_ids[i * WIN : i * WIN + WIN]
    t = torch.tensor(s, dtype=torch.long)
    return t[:-1], t[1:]


def _pad_window(seq, prompt_len=0):
    """Pad a short window to WIN tokens and mask both pad and prompt.

    Shared by the QA and pre-sliced paths. Pad positions get label -100 so they
    contribute nothing; truncating instead would throw away real tokens, which
    matters because sentence-aligned windows are deliberately short.

    `prompt_len` is the number of leading tokens that belong to the *question*
    ("User: ...\\nBot: "). Those positions are masked too: the model is asked to
    answer, and asking it to also reproduce the question spends gradient on the
    easy half of the sequence. Measured on the stories-as-chat corpus, 52.2% of
    the loss was exactly that. A window trains only its reply.
    """
    t = torch.tensor(seq, dtype=torch.long)
    if len(t) > WIN:
        t = t[:WIN]
    elif len(t) < WIN:
        t = torch.cat([t, torch.zeros(WIN - len(t), dtype=torch.long)])
    x, y = t[:-1], t[1:]
    # y[i] predicts t[i+1], so predicting the prompt means masking y[0 .. P-2].
    # y[P-1] is kept: it predicts t[P], the first reply token.
    n_real = min(len(seq), WIN) - 1
    n_mask_prompt = max(0, min(prompt_len - 1, block_size))
    n_mask_pad = max(0, block_size - n_real)
    if n_mask_prompt or n_mask_pad:
        y = y.clone()
        if n_mask_prompt:
            y[:n_mask_prompt] = -100
        if n_mask_pad:
            y[n_real:] = -100
    return x, y


def window_from_presliced(i):
    # Full-length window with no prompt mask is the overwhelmingly common case,
    # and it needs no padding and no masking -- so hand back views instead of
    # rebuilding the sequence.
    p = int(window_masks[i]) if window_masks is not None else 0
    n = int(win_lens[i])
    if n >= WIN and p == 0:
        t = torch.from_numpy(win_mat[i, :WIN]).long()
        return t[:-1], t[1:]
    return _pad_window(win_mat[i, :n], p)


