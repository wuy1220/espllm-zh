# ── Tokenizer：英文走 BPE，中文走字符级 ────────────────────────────────────
# 中文路线不训 BPE：一个汉字就是一个 token，词表大小由语料字频决定（实测 1256 条，
# 比英文 2048 省 68 KB Flash）。这里用 shim 类复刻 tokenizers 被用到的三个方法
# （get_vocab_size / encode().ids / decode），下游代码一行都不用改。
# 顺带修掉一个老问题：BPE 会把多字节汉字按字节切开，`decode([i])` 对单个字节返回
# U+FFFD，板上表现为偶发乱码；字符级分词从结构上不可能产生碎片。
class _Ids:
    __slots__ = ("ids",)

    def __init__(self, ids):
        self.ids = ids


class CharTokenizer:
    def __init__(self, path):
        import json as _json
        d = _json.load(open(path, encoding="utf-8"))
        self.chars = d["chars"]
        self.stoi = {c: i for i, c in enumerate(self.chars)}
        self.unk = self.stoi.get("<|endoftext|>", 0)

    def get_vocab_size(self):
        return len(self.chars)

    def encode(self, s):
        return _Ids([self.stoi.get(c, self.unk) for c in s])

    def decode(self, ids):
        ids = ids.tolist() if hasattr(ids, "tolist") else ids
        n = len(self.chars)
        return "".join(self.chars[i] for i in ids if 0 <= i < n)


