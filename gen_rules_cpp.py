"""Emit src/intent_rules_gen.h from intent_rules.py.

Only the Chinese frame layer is generated now. The English keyword tables
(~400 phrases, 20 intents, plus the exact/short/utter match modes they needed)
were removed together with the English model; what is left is 21 frames of
substring-matched Chinese, each with a small reply pool.

The generated shape is deliberately the same one that already runs on the
device: static PROGMEM pointer arrays plus an if-chain. A struct table read via
pgm_read_* would be shorter, but this firmware has already been broken three
times by flash-vs-RAM pointer mistakes, so the generated code stays on the one
pattern that is known to work here.
"""
import os
import sys

from intent_rules import (ZH_RULES, ZH_UNLESS, CONCEPT_NOUNS, GATED_FRAMES,
                          zh_clauses)

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "persona"))
from stance_lexicon import DEFLECT  # noqa: E402  回避池：zh_junk 帧的回复来源

OUT = os.path.join(HERE, "src", "intent_rules_gen.h")


def cstr(s):
    if '"' in s or "\\" in s:
        raise SystemExit(f"keyword/reply needs escaping, refuse to guess: {s!r}")
    return f'"{s}"'


def emit_keywords(label, kws, indent="    ", stem=None):
    """Emit one named PROGMEM string per keyword, then the pointer array.

    PROGMEM on `const char* arr[]` puts the *pointer table* in flash but leaves
    every literal it points at in .rodata -- which this core copies into DRAM at
    boot. With 9 hand-written keyword lists that cost ~700 B and went unnoticed;
    with 399 phrases it cost 4,172 B of a 8,192 B heap (RAM 89.2% -> 94.3%).
    Declaring each string as its own PROGMEM array is the fix, and it is the
    same form the replies already use.
    """
    out = []
    stem = stem or ("kKw" + label.capitalize())
    for i, kw in enumerate(kws):
        out.append(f"{indent}static const char {stem}_{i:02d}[] PROGMEM = {cstr(kw)};")
    out.append(f"{indent}static const char* const {stem}[] PROGMEM = {{")
    for i in range(0, len(kws), 6):
        chunk = ", ".join(f"{stem}_{j:02d}" for j in range(i, min(i + 6, len(kws))))
        out.append(f"{indent}    {chunk},")
    out.append(f"{indent}}};")
    return "\n".join(out)


def emit():
    L = []
    w = L.append
    w("// GENERATED by gen_rules_cpp.py from intent_rules.py -- do not edit.")
    w("// Edit intent_rules.py, re-run the generator, then run")
    w("// `python coverage_zh_rules.py` to confirm the firmware matches.")
    w("#ifndef INTENT_RULES_GEN_H")
    w("#define INTENT_RULES_GEN_H")
    w("")
    w("// 中文帧的回复池：同一帧随机取一条，这是设备端最便宜的多样性来源——")
    w("// 反复问同一句，措辞在 4~6 条里轮换，而不是同一句原样复读。")
    w("//")
    w("// 抽的时候躲两件事：上一条回复本身（同一个问题连问两次不复读），")
    w("// 以及首字已被禁的候选（和模型的禁首字共用同一个环，免得规则答完")
    w("// 模型又用同一个字开头）。全躲不开就退回随机那条。")
    w("static const char* pick_flash(const char* const* arr, size_t n) {")
    w("    if (n == 0) return NULL;")
    w("    size_t start = (size_t)(rand01() * (float)n);")
    w("    if (start >= n) start = n - 1;")
    w("    const char* fallback = (const char*)pgm_read_ptr(&arr[start]);")
    w("    for (size_t k = 0; k < n; ++k) {")
    w("        const char* p = (const char*)pgm_read_ptr(&arr[(start + k) % n]);")
    w("        if (p == s_last_flash) continue;")
    w("        if (flash_starts_banned(p)) continue;")
    w("        s_last_flash = p;")
    w("        return p;")
    w("    }")
    w("    s_last_flash = fallback;")
    w("    return fallback;")
    w("}")
    w("")
    w("// ---- 中文帧 -----------------------------------------------------------")
    w("// 关键词、回复池都在 intent_rules.py 里；这里是同一份数据的机器生成版。")
    w("// 匹配单位是子串（中文没有空格，字节 >= 0x80 时词边界判定恒为真），")
    w("// 长度闸用字节数：一个汉字 3 B。")
    for label, _gate, kws, _reps in ZH_RULES:
        cls = zh_clauses(kws)
        # 负关键词：单独一个 PROGMEM 字符串 + 指针数组，匹配条件里取反。
        # 必须在 `if not cls: continue` 之前发 —— 无关键词帧（zh_listen）
        # 也可以有除外词，否则条件引用了没定义的数组，直接编译失败。
        no = ZH_UNLESS.get(label)
        if no:
            w(emit_keywords(label + "_no", no, stem=_zh_kw(label) + "No"))
        if not cls:                  # zh_listen 没有关键词，只按长度兜
            continue
        if len(cls) == 1:
            w(emit_keywords(label, cls[0], stem=_zh_kw(label)))
        else:
            for i, c in enumerate(cls):
                w(emit_keywords(label, c, stem=f"{_zh_kw(label)}{i}"))
    w("")
    for label, _gate, _kws, reps in ZH_RULES:
        for i, r in enumerate(reps):
            w(f"    static const char {_zh_rep(label)}_{i:02d}[] PROGMEM = {cstr(r)};")
        arr = _zh_rep(label)
        w(f"    static const char* const {arr}[] PROGMEM = {{")
        for i in range(0, len(reps), 4):
            chunk = ", ".join(f"{arr}_{j:02d}" for j in range(i, min(i + 4, len(reps))))
            w(f"        {chunk},")
        w("    };")
    w("")
    # zh_junk 帧：关键词全部落空后，main.cpp 对"纯 ASCII 输入"直接抽这个池。
    # 词表 ASCII 只有 27 个，字母串/数字串/英文句进模型就是 UNK 序列，
    # 模型分不清"垃圾"和"没学过的问法"；"是不是中文"是元信息，归规则层。
    for i, r in enumerate(DEFLECT):
        w(f"    static const char kZhJunkRep_{i:02d}[] PROGMEM = {cstr(r)};")
    w("    static const char* const kZhJunkRep[] PROGMEM = {")
    for i in range(0, len(DEFLECT), 4):
        chunk = ", ".join(f"kZhJunkRep_{j:02d}" for j in range(i, min(i + 4, len(DEFLECT))))
        w(f"        {chunk},")
    w("    };")
    w(f"#define ZH_JUNK_REPS {len(DEFLECT)}")
    w("")
    # ---- 概念名词门（2026-10-22）----------------------------------------
    w("// 已配置概念的名词表：输入里出现任一个 = 用户在问模型学过的东西，")
    w("// 名词类帧（GATED_FRAMES）一律让位，交给模型自己答。")
    w("//")
    w("// 为什么需要：167 条模型训练过的问句里 35 条被规则半路截走，其中 24 条")
    w("// 模型本来答得对（_probe_overrule.py 板上实测）——「你会冻东西吗」「大酱")
    w("// 在哪」「你的符卡呢」被 capability/friend/spell 帧当成元问题。根因是帧的")
    w("// 关键词全是谓词（你会/认识/在哪），概念问句和元问句共用同一套谓词。")
    w("// 名词查表是 O(名词数) 次 strstr，输入 <64 B，成本可忽略。")
    for i, n in enumerate(CONCEPT_NOUNS):
        w(f"    static const char kZhConceptNoun_{i:03d}[] PROGMEM = {cstr(n)};")
    w("    static const char* const kZhConceptNoun[] PROGMEM = {")
    for i in range(0, len(CONCEPT_NOUNS), 6):
        chunk = ", ".join(f"kZhConceptNoun_{j:03d}"
                          for j in range(i, min(i + 6, len(CONCEPT_NOUNS))))
        w(f"        {chunk},")
    w("    };")
    w(f"#define ZH_CONCEPT_NOUNS {len(CONCEPT_NOUNS)}")
    w("")
    w("static bool zh_has_concept_noun(const char* norm) {")
    w("    return matches_any(norm, kZhConceptNoun, ZH_CONCEPT_NOUNS);")
    w("}")
    w("")
    w("static const char* match_intent_rules(const char* norm) {")
    w("    const int zh_bytes = (int)strlen(norm);")
    w("")
    for label, gate, _kws, reps in ZH_RULES:
        cls = zh_clauses(_kws)
        if cls:
            # 每个子句一个 matches_any，全部命中才成帧（子句内是"任一"）。
            cond = " && ".join(
                f"matches_any(norm, {arr}, sizeof({arr}) / sizeof(char*))"
                for arr in (
                    [_zh_kw(label)] if len(cls) == 1
                    else [f"{_zh_kw(label)}{i}" for i in range(len(cls))]
                ))
        else:
            cond = "1"               # 只有长度条件
        # 负关键词整句取反：出现例外词就不接（让给后面的帧或模型）。
        no = ZH_UNLESS.get(label)
        if no:
            no_arr = _zh_kw(label) + "No"
            cond = f"!matches_any(norm, {no_arr}, sizeof({no_arr}) / sizeof(char*)) && ({cond})"
        # 名词门：输入含已配置概念名词 -> 本帧让位给模型（只对名词类帧生效）。
        gated = label in GATED_FRAMES
        if gated:
            cond = f"!zh_has_concept_noun(norm) && ({cond})"
        if gate:
            cmp = ">=" if gate < 0 else "<="
            cond = f"zh_bytes {cmp} {abs(gate)} && ({cond})"
        gate_note = ("" if not gate else
                     ", >=%d B" % -gate if gate < 0 else ", <=%d B" % gate)
        if gated:
            gate_note += ", noun-gated"
        shape = ("%d 子句 AND" % len(cls)) if len(cls) > 1 else "%d phrases" % len(cls)
        unless_note = ", unless:%s" % "/".join(no) if no else ""
        w(f"    // {label} ({shape}, {len(reps)} replies{gate_note}{unless_note})")
        w(f"    if ({cond}) {{")
        w(f'        g_intent_label = "{label}";')
        w(f"        return pick_flash({_zh_rep(label)}, {len(reps)});")
        w("    }")
    w("    return NULL;")
    w("}")
    w("")
    w("#endif")
    return "\n".join(L) + "\n"


def _zh_kw(label):
    """zh_identity -> kZhIdentityKw。中文关键词数组名。"""
    return "kZh" + label[3:].capitalize() + "Kw"


def _zh_rep(label):
    return "kZh" + label[3:].capitalize() + "Rep"


if __name__ == "__main__":
    text = emit()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    nz = sum(sum(len(c) for c in zh_clauses(r[2])) for r in ZH_RULES)
    rz = sum(len(r[3]) for r in ZH_RULES)
    print(f"wrote {OUT}")
    print(f"  {len(ZH_RULES)} zh frames, {nz} keyword phrases, {rz} replies, "
          f"{len(text)} bytes")
